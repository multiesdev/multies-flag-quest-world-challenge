            "weekly_capitals", "Answer 10 capital questions" -> "weekly_capitals_title"
            "weekly_timed_level", "Complete a timed level" -> "weekly_timed_level_title"
            "weekly_score_500", "Score 500 points", "Accumulate 500 correct answers" -> "weekly_score_500_title"
            else -> if (key.endsWith("_title")) key else "${key}_title"
        }
        return get(templateKey, lang, context)
    }

