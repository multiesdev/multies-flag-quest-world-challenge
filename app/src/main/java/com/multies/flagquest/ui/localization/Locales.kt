    fun get(key: String, lang: String, context: android.content.Context? = null): String {
        if (context != null) {
            try {
                val locale = when (lang.lowercase()) {
                    "ar" -> java.util.Locale("ar")
                    "de" -> java.util.Locale("de")
                    "fr" -> java.util.Locale("fr")
                    else -> java.util.Locale("en")
                }
                val config = android.content.res.Configuration(context.resources.configuration)
                config.setLocale(locale)
                val localizedContext = context.createConfigurationContext(config)
                val resId = localizedContext.resources.getIdentifier(key, "string", localizedContext.packageName)
                if (resId != 0) {
                    val str = localizedContext.getString(resId)
                    if (str.isNotEmpty()) return str
                }
            } catch (e: Exception) {
                // fallback to dictionary
            }
        }
        val dict = translations[lang] ?: translations["en"]!!
        return dict[key] ?: translations["en"]!![key] ?: key
    }

